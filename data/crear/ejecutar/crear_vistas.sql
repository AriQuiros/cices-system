JOIN PROYECTO p ON p.ID_PROYECTO = ep.ID_PROYECTO
JOIN ENTIDAD e ON e.ID_ENTIDAD = ep.ID_ENTIDAD
ORDER BY 1;

PROMPT == REP_PROYECTO_PRESENTACION_INFORME ==
CREATE OR REPLACE VIEW REP_PROYECTO_PRESENTACION_INFORME AS
SELECT
  pinf.ID_PRESENTACION_INFORME,
  p.ID_PROYECTO,
  c_inf.DESPLIEGUE AS TIPO_INFORME,
  c_est.DESPLIEGUE AS ESTADO_INFORME,
  pinf.FECHA_PRESENTACION
FROM PRESENTACION_INFORME pinf
JOIN PROYECTO p ON p.ID_PROYECTO = pinf.ID_PROYECTO
LEFT JOIN CODIGO c_inf ON c_inf.ID_CODIGO = pinf.ID_CODIGO_TIPO_INFORME
LEFT JOIN CODIGO c_est ON c_est.ID_CODIGO = pinf.ID_CODIGO_TIPO_ESTADO
ORDER BY 1;

PROMPT == REP_PRESUPUESTO_BASE ==
CREATE OR REPLACE VIEW REP_PRESUPUESTO_BASE AS
SELECT
  pr.ID_PRESUPUESTO,
  p.ID_PROYECTO,
  p.CODIGO_PROYECTO,
  c_tip.DESPLIEGUE AS TIPO_PRESUPUESTO,
  c_fue.DESPLIEGUE AS FUENTE_FINANCIAMIENTO,
  c_cat.DESPLIEGUE AS CATEGORIA_PRESUPUESTO,
  pr.DESCRIPCION,
  pr.CANTIDAD_HORAS_MES,
  pr.CANTIDAD_MESES,
  pr.MONTO_ASIGNADO,
  pr.FECHA_ASIGNACION
FROM PRESUPUESTO pr
JOIN PROYECTO p ON p.ID_PROYECTO = pr.ID_PROYECTO
LEFT JOIN CODIGO c_cat ON c_cat.ID_CODIGO = pr.ID_CODIGO_TIPO_CATEGORIA
LEFT JOIN CODIGO c_fue ON c_fue.ID_CODIGO = pr.ID_CODIGO_TIPO_FUENTE_FINANCIAMIENTO
LEFT JOIN CODIGO c_tip ON c_tip.ID_CODIGO = pr.ID_CODIGO_TIPO_PRESUPUESTO
ORDER BY 1;

PROMPT == REP_PRESUPUESTO_GASTOS ==
CREATE OR REPLACE VIEW REP_PRESUPUESTO_GASTOS AS
SELECT
  g.ID_GASTO,
  pr.ID_PRESUPUESTO,
  g.MONTO,
  g.FECHA_GASTO,
  g.DESCRIPCION
FROM GASTO g
JOIN PRESUPUESTO pr ON pr.ID_PRESUPUESTO = g.ID_PRESUPUESTO
ORDER BY 1;

PROMPT == REP_PRESUPUESTO_HORAS ==
CREATE OR REPLACE VIEW REP_PRESUPUESTO_HORAS AS
SELECT
  h.ID_HORAS_ASIGNADAS,
  ip.ID_INVESTIGADOR_PROYECTO,
  ip.ID_PROYECTO,
  pr.ID_PRESUPUESTO,
  e.IDENTIFICACION,
  e.NOMBRE_COMPLETO,
  ip.FECHA_INICIO_INVESTIGADOR,
  ip.FECHA_FIN_INVESTIGADOR,
  h.CANTIDAD_HORAS_MES,
  h.CANTIDAD_MESES,
  c.DESPLIEGUE AS MODALIDAD
FROM INVESTIGADOR_PROYECTO ip
JOIN INVESTIGADOR i ON i.ID_INVESTIGADOR = ip.ID_INVESTIGADOR
JOIN EMPLEADO e ON e.ID_EMPLEADO = i.ID_EMPLEADO
LEFT JOIN HORAS_ASIGNADAS h ON h.ID_INVESTIGADOR_PROYECTO = ip.ID_INVESTIGADOR_PROYECTO
LEFT JOIN PRESUPUESTO pr ON pr.ID_PRESUPUESTO = h.ID_PRESUPUESTO
LEFT JOIN CODIGO c ON c.ID_CODIGO = h.ID_CODIGO_TIPO_MODALIDAD
ORDER BY 1;

PROMPT == REP_NOTIFICACIONES_USUARIO ==
CREATE OR REPLACE VIEW REP_NOTIFICACIONES_USUARIO AS
SELECT
  nu.ID_NOTIFICACION_USUARIO,
  u.ID_USUARIO,
  u.NOMBRE_USUARIO,
  n.ID_NOTIFICACION,
  n.ASUNTO,
  n.MENSAJE,
  c_cat.DESPLIEGUE AS CATEGORIA,
  nu.LEIDO,
  n.FECHA_CREACION,
  nu.FECHA_LEIDO
FROM NOTIFICACION_USUARIO nu
JOIN NOTIFICACION n ON n.ID_NOTIFICACION = nu.ID_NOTIFICACION
JOIN USUARIO u ON u.ID_USUARIO = nu.ID_USUARIO
LEFT JOIN CODIGO c_cat ON c_cat.ID_CODIGO = n.ID_CODIGO_TIPO_CATEGORIA
ORDER BY 1;

PROMPT == REP_RESUMEN_EJECUTIVO ==
CREATE OR REPLACE VIEW REP_RESUMEN_EJECUTIVO AS
SELECT
  FUN_CANT_USUARIOS AS TOTAL_USUARIOS,
  FUN_CANT_INVESTIGADORES AS INVESTIGADORES_REGISTRADOS,
  FUN_CANT_USUARIOS_POR_ROL('ADMINISTRATIVO') AS ADMINISTRATIVOS,
  FUN_CANT_USUARIOS_POR_ROL('ASISTENTE') AS ASISTENTES,
  FUN_CANT_USUARIOS_POR_ROL('DIRECCION') AS DIRECTORES,
  FUN_CANT_USUARIOS_INACTIVOS AS USUARIOS_INACTIVOS,
  FUN_CANT_INVESTIGADORES_CON_USUARIO_INACTIVO AS INVESTIGADORES_USUARIO_INACTIVO,
  FUN_CANT_PROYECTOS AS TOTAL_PROYECTOS,
  FUN_CANT_PROYECTOS_POR_ESTADO('ACTIVO') AS PROYECTOS_ACTIVOS,
  FUN_CANT_PROYECTOS_POR_ESTADO('FINALIZADO') AS PROYECTOS_INACTIVOS,
  FUN_CANT_CERTIFICACIONES_VENCIDAS AS CERTIFICACIONES_VENCIDAS,
  FUN_CANT_CERTIFICACIONES_POR_VENCER AS CERTIFICACIONES_POR_VENCER,
  FUN_CANT_CERTIFICACIONES_ACTIVAS AS CERTIFICACIONES_VIGENTES
FROM DUAL;

