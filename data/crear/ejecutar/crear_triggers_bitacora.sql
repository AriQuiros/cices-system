CREATE OR REPLACE TRIGGER PRESUPUESTO_TRG_AUR
AFTER UPDATE ON PRESUPUESTO
FOR EACH ROW
BEGIN
  IF NVL(:OLD.MONTO_ASIGNADO,0) != NVL(:NEW.MONTO_ASIGNADO,0) THEN
    INSERT INTO PRESUPUESTO_BIT (
      ID_PRESUPUESTO_BIT,
      FEC_BIT, ACC_BIT, USU_BIT,
      ID_PRESUPUESTO, ID_PROYECTO,
      MONTO_ASIGNADO_OLD, CANTIDAD_HORAS_MES_OLD, CANTIDAD_MESES_OLD,
      MONTO_ASIGNADO_NEW, CANTIDAD_HORAS_MES_NEW, CANTIDAD_MESES_NEW
    ) VALUES (
      SEC_PRESUPUESTO_BIT.NEXTVAL,
      SYSDATE, 'U', USER,
      :OLD.ID_PRESUPUESTO, :OLD.ID_PROYECTO,
      :OLD.MONTO_ASIGNADO, :OLD.CANTIDAD_HORAS_MES, :OLD.CANTIDAD_MESES,
      :NEW.MONTO_ASIGNADO, :NEW.CANTIDAD_HORAS_MES, :NEW.CANTIDAD_MESES
    );
  END IF;
END;
/
SHOW ERRORS


exit
