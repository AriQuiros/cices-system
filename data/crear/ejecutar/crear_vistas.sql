JOIN PROYECTO p ON p.ID_PROYECTO = ep.ID_PROYECTO
JOIN ENTIDAD e  ON e.ID_ENTIDAD = ep.ID_ENTIDAD
ORDER BY 1;
/ 

PROMPT == REP_PROYECTO_PRESENTACION_INFORME ==
