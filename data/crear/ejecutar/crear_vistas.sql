PROMPT == REP_PERSONA_USUARIA ==
CREATE OR REPLACE VIEW REP_PERSONA_USUARIA AS
SELECT
  e.ID_EMPLEADO,
  e.NOMBRE_COMPLETO,
  e.IDENTIFICACION,
  c_id.DESPLIEGUE AS TIPO_IDENTIFICACION,
  e.PAIS,
  e.CORREO,
  e.NUMERO_TELEFONO,
  c_grad.DESPLIEGUE AS GRADO_ACADEMICO,
  i.ID_INVESTIGADOR,
  ent.NOMBRE AS INSTITUCION_ORIGEN,
  uni.NOMBRE AS UNIDAD_ACADEMICA,
  i.TEMA_INTERES,
  ru.ID_ROL_USUARIO,
  u.ID_USUARIO,
  u.NOMBRE_USUARIO,
  u.ACTIVO,
  r.NOMBRE_ROL
FROM EMPLEADO e
LEFT JOIN INVESTIGADOR i ON i.ID_EMPLEADO = e.ID_EMPLEADO
LEFT JOIN ENTIDAD ent ON ent.ID_ENTIDAD = i.ID_INSTITUCION_ORIGEN
LEFT JOIN ENTIDAD uni ON uni.ID_ENTIDAD = i.ID_UNIDAD_ACADEMICA
LEFT JOIN CODIGO c_id  ON c_id.ID_CODIGO = e.ID_CODIGO_TIPO_ID
LEFT JOIN CODIGO c_grad ON c_grad.ID_CODIGO = e.ID_CODIGO_TIPO_GRADO_ACADEMICO
LEFT JOIN USUARIO u ON u.ID_USUARIO = e.ID_USUARIO
LEFT JOIN ROL_USUARIO ru ON ru.ID_USUARIO = u.ID_USUARIO
LEFT JOIN ROL r  ON r.ID_ROL = ru.ID_ROL;

PROMPT == REP_INVESTIGADOR_TITULOS ==
CREATE OR REPLACE VIEW REP_INVESTIGADOR_TITULOS AS
SELECT
  t.ID_TITULO,
  i.ID_INVESTIGADOR,
  e.NOMBRE_COMPLETO AS NOMBRE_INVESTIGADOR,
  e.IDENTIFICACION,
  t.NOMBRE_TITULO,
  c.DESPLIEGUE AS NIVEL_TITULO,
  ent.NOMBRE AS INSTITUCION,
  t.FECHA_EMISION
FROM TITULO t
JOIN INVESTIGADOR i ON i.ID_INVESTIGADOR = t.ID_INVESTIGADOR
JOIN EMPLEADO e ON e.ID_EMPLEADO = i.ID_EMPLEADO
JOIN ENTIDAD ent ON ent.ID_ENTIDAD = t.ID_ENTIDAD
LEFT JOIN CODIGO c ON c.ID_CODIGO = t.ID_CODIGO_TIPO_NIVEL_TITULO
ORDER BY 1;

PROMPT == REP_INVESTIGADOR_CERTIFICACIONES ==
CREATE OR REPLACE VIEW REP_INVESTIGADOR_CERTIFICACIONES AS
SELECT
  ctf.ID_CERTIFICACION,
  i.ID_INVESTIGADOR,
  e.IDENTIFICACION,
  e.NOMBRE_COMPLETO AS NOMBRE_INVESTIGADOR,
  ctf.NOMBRE_CERTIFICACION,
  c_tipo.DESPLIEGUE AS TIPO_CERTIFICACION,
  ent.NOMBRE AS INSTITUCION,
  c_est.DESPLIEGUE AS ESTADO_CERTIFICACION,
  ctf.FECHA_EXPIRACION
FROM CERTIFICACION ctf
JOIN INVESTIGADOR i ON i.ID_INVESTIGADOR = ctf.ID_INVESTIGADOR
JOIN EMPLEADO e ON e.ID_EMPLEADO = i.ID_EMPLEADO
JOIN ENTIDAD ent ON ent.ID_ENTIDAD = ctf.ID_ENTIDAD
LEFT JOIN CODIGO c_tipo ON c_tipo.ID_CODIGO = ctf.ID_CODIGO_TIPO_CERTIFICACION
LEFT JOIN CODIGO c_est ON c_est.ID_CODIGO = ctf.ID_CODIGO_TIPO_ESTADO
ORDER BY 1;

PROMPT == REP_PROYECTO_BASE ==
CREATE OR REPLACE VIEW REP_PROYECTO_BASE AS
SELECT
  p.ID_PROYECTO,
  p.CODIGO_PROYECTO,
  p.NOMBRE_PROYECTO,
  p.DESCRIPCION_PROYECTO,
  p.OBJETIVO_GENERAL,
  p.LINEA_INVESTIGACION,
  c_est.DESPLIEGUE AS ESTADO_PROYECTO,
  c_tipo.DESPLIEGUE AS TIPO_PROYECTO,
  p.FECHA_INICIO,
  p.FECHA_FINALIZACION
FROM PROYECTO p
LEFT JOIN CODIGO c_est ON c_est.ID_CODIGO = p.ID_CODIGO_TIPO_ESTADO
LEFT JOIN CODIGO c_tipo ON c_tipo.ID_CODIGO = p.ID_CODIGO_TIPO_PROYECTO
ORDER BY 1;

PROMPT == REP_INVESTIGADOR_PROYECTO ==
CREATE OR REPLACE VIEW REP_INVESTIGADOR_PROYECTO AS
SELECT
  ip.ID_INVESTIGADOR_PROYECTO,
  p.ID_PROYECTO,
  p.CODIGO_PROYECTO,
  p.NOMBRE_PROYECTO,
  i.ID_INVESTIGADOR,
  e.NOMBRE_COMPLETO AS NOMBRE_INVESTIGADOR,
  e.IDENTIFICACION,
  rp.NOMBRE_ROL_PROYECTO AS ROL_PROYECTO,
  ip.ACTIVIDAD_PROYECTO,
  ip.FECHA_INICIO_INVESTIGADOR,
  ip.FECHA_FIN_INVESTIGADOR,
  pp.ID_PERMISO_PROYECTO,
  pp.FECHA_INICIO_PERMISO,
  pp.FECHA_FIN_PERMISO
FROM INVESTIGADOR_PROYECTO ip
JOIN INVESTIGADOR i ON i.ID_INVESTIGADOR = ip.ID_INVESTIGADOR
JOIN EMPLEADO e ON e.ID_EMPLEADO = i.ID_EMPLEADO
JOIN PROYECTO p ON p.ID_PROYECTO = ip.ID_PROYECTO
JOIN ROL_PROYECTO rp ON rp.ID_ROL_PROYECTO = ip.ID_ROL_PROYECTO
LEFT JOIN PERMISO_PROYECTO pp ON pp.ID_INVESTIGADOR_PROYECTO = ip.ID_INVESTIGADOR_PROYECTO
ORDER BY 1;

PROMPT == REP_PROYECTO_RESULTADOS ==
CREATE OR REPLACE VIEW REP_PROYECTO_RESULTADOS AS
SELECT
  p.ID_PROYECTO,
  p.NOMBRE_PROYECTO,
  p.CODIGO_PROYECTO,
  oe.ID_OBJETIVO_ESPECIFICO,
  oe.DESCRIPCION AS OBJETIVO_ESPECIFICO,
  m.ID_META,
  m.DESCRIPCION AS META,
  c.DESPLIEGUE AS TIPO_META,
  m.CANTIDAD AS CANTIDAD_META,
  i.ID_INDICADOR,
  i.DESCRIPCION AS INDICADOR
FROM PROYECTO p
JOIN OBJETIVO_ESPECIFICO oe ON oe.ID_PROYECTO = p.ID_PROYECTO
JOIN META m ON m.ID_OBJETIVO_ESPECIFICO = oe.ID_OBJETIVO_ESPECIFICO
LEFT JOIN INDICADOR i ON i.ID_META = m.ID_META
LEFT JOIN CODIGO c ON c.ID_CODIGO = m.ID_CODIGO_TIPO_META
ORDER BY 1;

PROMPT == REP_PROYECTO_DOCUMENTOS ==
CREATE OR REPLACE VIEW REP_PROYECTO_DOCUMENTOS AS
SELECT
  d.ID_DOCUMENTO,
  p.ID_PROYECTO,
  d.NOMBRE_DOCUMENTO
FROM DOCUMENTO d
JOIN PROYECTO p ON p.ID_PROYECTO = d.ID_PROYECTO
ORDER BY 1;

PROMPT == REP_ENTIDAD_PROYECTO ==
CREATE OR REPLACE VIEW REP_ENTIDAD_PROYECTO AS
SELECT
  ep.ID_ENTIDAD_PROYECTO,
  p.ID_PROYECTO,
  p.NOMBRE_PROYECTO,
  p.CODIGO_PROYECTO,
  e.NOMBRE AS NOMBRE_ENTIDAD
