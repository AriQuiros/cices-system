PROMPT === TRIGGERS CERTIFICACION ================
PROMPT ===========================================

-- BEFORE INSERT: estado inicial
CREATE OR REPLACE TRIGGER CERTIFICACION_TRG_BIR
BEFORE INSERT ON CERTIFICACION
FOR EACH ROW
BEGIN
  IF :NEW.FECHA_EXPIRACION IS NULL THEN
    :NEW.ID_CODIGO_TIPO_ESTADO := 12; 
  ELSIF :NEW.FECHA_EXPIRACION < SYSDATE THEN
    :NEW.ID_CODIGO_TIPO_ESTADO := 14; 
  ELSIF :NEW.FECHA_EXPIRACION <= ADD_MONTHS(SYSDATE, 3) THEN
    :NEW.ID_CODIGO_TIPO_ESTADO := 13; 
  ELSE
    :NEW.ID_CODIGO_TIPO_ESTADO := 12; 
  END IF;
END;
