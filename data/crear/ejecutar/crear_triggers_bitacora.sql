PROMPT === TRIGGERS DE BITÁCORA (OLD / NEW) =======
PROMPT ===========================================


DROP TRIGGER PRESUPUESTO_TRG_AIR;
DROP TRIGGER PRESUPUESTO_TRG_AUR;
DROP TRIGGER PRESUPUESTO_TRG_ADR;


PROMPT ===========================================
PROMPT === TRIGGERS INSERT =======
PROMPT ===========================================


CREATE OR REPLACE TRIGGER PRESUPUESTO_TRG_AIR
AFTER INSERT ON PRESUPUESTO
FOR EACH ROW
BEGIN
  INSERT INTO PRESUPUESTO_BIT (
    ID_BIT, FEC_BIT, ACC_BIT, USU_BIT,
    ID_PRESUPUESTO, ID_PROYECTO, MONTO_ASIGNADO_OLD, CANTIDAD_HORAS_MES_OLD, CANTIDAD_MESES_OLD, MONTO_ASIGNADO_NEW, CANTIDAD_HORAS_MES_NEW, CANTIDAD_MESES_NEW
  ) VALUES (
    SEC_PRESUPUESTO_BIT.NEXTVAL,
    SYSDATE,
    'I',
    USER,
    :NEW.ID_PRESUPUESTO, :NEW.ID_PROYECTO, NULL, NULL, NULL, :NEW.MONTO_ASIGNADO, :NEW.CANTIDAD_HORAS_MES, :NEW.CANTIDAD_MESES
  );
END;
