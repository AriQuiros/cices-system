PROMPT == FUN_CANT_USUARIOS_POR_ROL ==
CREATE OR REPLACE FUNCTION FUN_CANT_USUARIOS_POR_ROL(PRol IN VARCHAR2)
RETURN NUMBER IS
  VResultado NUMBER;
BEGIN
  SELECT COUNT(DISTINCT u.ID_USUARIO)
  INTO   VResultado
  FROM   USUARIO u
  JOIN   ROL_USUARIO ru ON ru.ID_USUARIO = u.ID_USUARIO
  JOIN   ROL r ON r.ID_ROL = ru.ID_ROL
  WHERE  UPPER(r.NOMBRE_ROL) = UPPER(PRol);

  RETURN VResultado;
EXCEPTION
  WHEN OTHERS THEN
    RETURN 0;
END FUN_CANT_USUARIOS_POR_ROL;
