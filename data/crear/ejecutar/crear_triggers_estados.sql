PROMPT == TB_IU_R_CERTIFICACION_ESTADO ==
CREATE OR REPLACE TRIGGER TB_IU_R_CERTIFICACION_ESTADO
BEFORE INSERT OR UPDATE ON CERTIFICACION
FOR EACH ROW
DECLARE
    VDIAS NUMBER;
BEGIN
    IF :NEW.FECHA_EXPIRACION IS NOT NULL THEN
        VDIAS := TRUNC(:NEW.FECHA_EXPIRACION - SYSDATE);

        IF VDIAS < 0 THEN
            :NEW.ID_CODIGO_TIPO_ESTADO := FUN_OBTENER_CODIGO('ESTADO_CERTIFICACION','VENCIDA');

        ELSIF VDIAS > 90 THEN
            :NEW.ID_CODIGO_TIPO_ESTADO := FUN_OBTENER_CODIGO('ESTADO_CERTIFICACION','VIGENTE');

        ELSE
            :NEW.ID_CODIGO_TIPO_ESTADO := FUN_OBTENER_CODIGO('ESTADO_CERTIFICACION','PROXIMA A VENCER');
        END IF;

    ELSE
        :NEW.ID_CODIGO_TIPO_ESTADO := FUN_OBTENER_CODIGO('ESTADO_CERTIFICACION','VIGENTE');
    END IF;
END;
/
SHOW ERROR


PROMPT == TB_IU_R_INFORME_ESTADO ==
CREATE OR REPLACE TRIGGER TB_IU_R_INFORME_ESTADO
BEFORE INSERT OR UPDATE ON PRESENTACION_INFORME
FOR EACH ROW
BEGIN
    IF :NEW.FECHA_PRESENTACION >= TRUNC(SYSDATE) THEN
        :NEW.ID_CODIGO_TIPO_ESTADO := FUN_OBTENER_CODIGO('ESTADO_INFORME','PENDIENTE');
    ELSE
        :NEW.ID_CODIGO_TIPO_ESTADO := FUN_OBTENER_CODIGO('ESTADO_INFORME','ENTREGADO');
    END IF;
END;
/
SHOW ERROR


