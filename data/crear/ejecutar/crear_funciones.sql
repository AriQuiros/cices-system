CREATE OR REPLACE FUNCTION FUN_CANT_INVESTIGADORES_CON_USUARIO_INACTIVO
RETURN NUMBER IS
  VResultado NUMBER;
BEGIN
  SELECT COUNT(DISTINCT i.ID_INVESTIGADOR)
  INTO   VResultado
  FROM   INVESTIGADOR i
  JOIN   EMPLEADO e ON e.ID_EMPLEADO = i.ID_EMPLEADO
  JOIN   USUARIO u ON u.ID_USUARIO = e.ID_USUARIO
  WHERE  u.ACTIVO = 0;

  RETURN VResultado;
EXCEPTION
  WHEN OTHERS THEN
    RETURN 0;
END FUN_CANT_INVESTIGADORES_CON_USUARIO_INACTIVO;
