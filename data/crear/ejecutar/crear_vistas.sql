SELECT
  pinf.ID_PRESENTACION_INFORME,
  p.ID_PROYECTO,
  p.CODIGO_PROYECTO,
  p.NOMBRE_PROYECTO,
  pinf.ID_CODIGO_TIPO_INFORME,
  c_inf.DESPLIEGUE AS TIPO_INFORME,
