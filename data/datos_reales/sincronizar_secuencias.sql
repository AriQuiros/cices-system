PROMPT Verificando secuencia SEC_CERTIFICACION
SELECT NVL(MAX(ID_CERTIFICACION),0) FROM CICES.CERTIFICACION;
PROMPT Ajustando secuencia SEC_CERTIFICACION
DECLARE
  max_id   NUMBER;
  curr_val NUMBER;
BEGIN
  SELECT NVL(MAX(ID_CERTIFICACION),0) INTO max_id FROM CICES.CERTIFICACION;
  EXECUTE IMMEDIATE 'SELECT CICES.SEC_CERTIFICACION.NEXTVAL FROM DUAL' INTO curr_val;
  EXECUTE IMMEDIATE 'ALTER SEQUENCE CICES.SEC_CERTIFICACION INCREMENT BY ' || (max_id + 1 - curr_val);
  EXECUTE IMMEDIATE 'SELECT CICES.SEC_CERTIFICACION.NEXTVAL FROM DUAL' INTO curr_val;
  EXECUTE IMMEDIATE 'ALTER SEQUENCE CICES.SEC_CERTIFICACION INCREMENT BY 1';
  DBMS_OUTPUT.PUT_LINE('    → SEC_CERTIFICACION sincronizada correctamente en: ' || curr_val);
END;
