PROMPT == FUN_OBTENER_CODIGO ==
CREATE OR REPLACE FUNCTION FUN_OBTENER_CODIGO(
    PTIPO   IN VARCHAR2,
    PVALOR  IN VARCHAR2
) RETURN NUMBER IS
    VRESULTADO NUMBER;
BEGIN
    SELECT C.ID_CODIGO
    INTO   VRESULTADO
    FROM   CODIGO C
    JOIN   TIPO T ON T.ID_TIPO = C.ID_TIPO
    WHERE  UPPER(T.NOMBRE) = UPPER(PTIPO)
    AND    UPPER(C.VALOR) = UPPER(PVALOR);

    RETURN VRESULTADO;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL;
    WHEN OTHERS THEN
        RETURN NULL;
END FUN_OBTENER_CODIGO;
/
