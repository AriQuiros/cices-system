CREATE OR REPLACE TRIGGER TB_IU_R_PROYECTO_ESTADO
BEFORE INSERT OR UPDATE ON PROYECTO
FOR EACH ROW
BEGIN
    IF :NEW.FECHA_FINALIZACION IS NOT NULL 
       AND :NEW.FECHA_FINALIZACION < TRUNC(SYSDATE) THEN

        :NEW.ID_CODIGO_TIPO_ESTADO := FUN_OBTENER_CODIGO('ESTADO_PROYECTO','FINALIZADO');

    ELSE
        :NEW.ID_CODIGO_TIPO_ESTADO := FUN_OBTENER_CODIGO('ESTADO_PROYECTO','ACTIVO');
    END IF;
END;
